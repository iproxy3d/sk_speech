def render_module(relative: str, title: str, summary: str) -> str:
    tree = module_tree(relative)
    module = relative.removesuffix(".py").replace("/", ".")
    lines = [
        f"# {title}",
        "",
        "[← К оглавлению API](../API.md)",
        "",
        f"Модуль: `sk_speech.{module}`.",
        "",
        summary,
        "",
    ]
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and not node.name.startswith("_"):
            description = CLASS_DESCRIPTIONS.get(node.name) or clean_doc(ast.get_docstring(node)) or "Класс состояния или контейнер данных этой подсистемы."
            lines += [f"## Класс `{node.name}`", "", description, "", "```python", class_constructor(node), "```", ""]
            public_methods = [item for item in node.body if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)) and not item.name.startswith("_")]
            for method in public_methods:
                lines.extend(function_block(method, module=relative, owner=node.name))
    functions = [node for node in tree.body if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and not node.name.startswith("_")]
    if functions:
        lines += ["## Функции", ""]
        for function in functions:
            lines.extend(function_block(function, module=relative))
    return "\n".join(lines).rstrip() + "\n"


